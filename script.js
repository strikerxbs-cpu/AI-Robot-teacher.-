// ========================================
// Random Shuffle
// ========================================

function shuffle(array) {

  for (
    let i = array.length - 1;
    i > 0;
    i--
  ) {

    const j =
      Math.floor(Math.random() * (i + 1));

    [
      array[i],
      array[j]
    ] = [
      array[j],
      array[i]
    ];

  }

  return array;

}


// ========================================
// Quiz শুরু
// ========================================

function startQuiz() {

  const count =
    Number(
      document.getElementById("questionCount").value
    );

  const bank =
    quizData[selectedSubject];

  if (!bank || bank.length === 0) {

    alert(
      "এই Subject-এর প্রশ্ন এখনো যোগ করা হয়নি।"
    );

    return;

  }

  questions =
    shuffle([...bank]).slice(
      0,
      Math.min(count, bank.length)
    );

  currentQuestion = 0;

  score = 0;

  quizFinished = false;

  document.getElementById("setup")
    .classList.add("hidden");

  document.getElementById("quiz")
    .classList.remove("hidden");

  showQuestion();

}


// ========================================
// Question দেখানো
// ========================================

function showQuestion() {

  const q =
    questions[currentQuestion];

  document.getElementById("questionNumber")
    .innerText =
    `প্রশ্ন ${currentQuestion + 1} / ${questions.length}`;

  document.getElementById("score")
    .innerText =
    `Score: ${score}`;

  document.getElementById("question")
    .innerText =
    q.question;

  document.getElementById("feedback")
    .innerText = "";

  const progress =
    ((currentQuestion) / questions.length) * 100;

  document.getElementById("progressBar")
    .style.width =
    progress + "%";

  const optionsBox =
    document.getElementById("options");

  optionsBox.innerHTML = "";

  q.options.forEach(
    (option, index) => {

      const button =
        document.createElement("button");

      button.className = "option";

      button.innerText =
        `${String.fromCharCode(65 + index)}. ${option}`;

      button.onclick =
        () => checkAnswer(index, button);

      optionsBox.appendChild(button);

    }
  );

}


// ========================================
// উত্তর যাচাই
// ========================================

function checkAnswer(selected, button) {

  if (quizFinished) return;

  const q =
    questions[currentQuestion];

  const buttons =
    document.querySelectorAll(".option");

  buttons.forEach(
    btn => btn.disabled = true
  );

  if (selected === q.answer) {

    score++;

    button.classList.add("correct");

    document.getElementById("feedback")
      .innerText =
      "✅ সঠিক উত্তর! খুব ভালো!";

    speak("সঠিক উত্তর! খুব ভালো!");

  } else {

    button.classList.add("wrong");

    buttons[q.answer]
      .classList.add("correct");

    document.getElementById("feedback")
      .innerText =
      "❌ ভুল উত্তর!";

    speak("ভুল উত্তর।");

  }

  setTimeout(
    () => {

      currentQuestion++;

      if (
        currentQuestion < questions.length
      ) {

        showQuestion();

      } else {

        finishQuiz();

      }

    },
    900
  );

}


// ========================================
// Quiz শেষ
// ========================================

function finishQuiz() {

  quizFinished = true;

  document.getElementById("quiz")
    .classList.add("hidden");

  document.getElementById("result")
    .classList.remove("hidden");

  const percentage =
    Math.round(
      (score / questions.length) * 100
    );

  document.getElementById("percentage")
    .innerText =
    percentage + "%";

  document.getElementById("resultText")
    .innerText =
    `সঠিক উত্তর: ${score}টি
     • ভুল উত্তর: ${questions.length - score}টি
     • মোট প্রশ্ন: ${questions.length}টি`;

  if (percentage >= 80) {

    speak(
      "দারুণ! তুমি অসাধারণ ফলাফল করেছো!"
    );

  } else if (percentage >= 50) {

    speak(
      "খুব ভালো! আরও একটু অনুশীলন করো।"
    );

  } else {

    speak(
      "চেষ্টা চালিয়ে যাও। তুমি আরও ভালো করতে পারবে।"
    );

  }

}


