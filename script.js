// ========================================
// 🤖 বাংলা Robot Voice
// ========================================

function speak(text) {

  if (!("speechSynthesis" in window)) {

    return;

  }

  speechSynthesis.cancel();

  const voice =
    new SpeechSynthesisUtterance(text);

  voice.lang = "bn-BD";

  voice.rate = 0.9;

  voice.pitch = 1;

  voice.volume = 1;

  const voices =
    speechSynthesis.getVoices();

  const banglaVoice =
    voices.find(
      v =>
        v.lang &&
        v.lang.toLowerCase().startsWith("bn")
    );

  if (banglaVoice) {

    voice.voice =
      banglaVoice;

  }

  speechSynthesis.speak(voice);

}


